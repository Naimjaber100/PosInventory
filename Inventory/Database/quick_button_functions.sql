-- Cashier quick buttons ("POS buttons"): items without a barcode (bread, vegetables, restaurant dishes...)
-- shown as buttons on the right side of the cashier screen, sorted into tabs (Salads, Drinks...).
-- Managed in the back office (Item > Quick buttons). A tab is a row of pos_quick_groups.
-- No tabs = all buttons on one page (simple shop); with tabs the cashier taps a tab, then the item.
-- Safe to re-run: tables are created / extended once, functions are dropped and recreated.
-- Apply:  psql -h localhost -U postgres -d Pos -f quick_button_functions.sql

CREATE TABLE IF NOT EXISTS public.pos_quick_groups (
    group_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(40) NOT NULL,
    color      varchar(7),                          -- '#RRGGBB', null = default
    sort_order integer NOT NULL DEFAULT 0,
    is_active  boolean NOT NULL DEFAULT true,       -- false = hidden on the cashier screen
    CONSTRAINT pos_quick_groups_color_check CHECK (color IS NULL OR color ~ '^#[0-9A-Fa-f]{6}$')
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_pos_quick_groups_name ON public.pos_quick_groups (lower(name));

CREATE TABLE IF NOT EXISTS public.pos_quick_buttons (
    button_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    packaging_id integer NOT NULL UNIQUE REFERENCES product_packaging(packaging_id) ON DELETE CASCADE,
    caption      varchar(40),                       -- null = the item name
    color        varchar(7),                        -- '#RRGGBB', null = the tab's color
    sort_order   integer NOT NULL DEFAULT 0,        -- order inside its tab
    is_active    boolean NOT NULL DEFAULT true,
    CONSTRAINT pos_quick_buttons_color_check CHECK (color IS NULL OR color ~ '^#[0-9A-Fa-f]{6}$')
);
-- null = no tab ("Other" on the cashier screen when tabs exist)
ALTER TABLE public.pos_quick_buttons
    ADD COLUMN IF NOT EXISTS group_id integer REFERENCES pos_quick_groups(group_id) ON DELETE SET NULL;
-- true = the cashier types the price when selling it (open price)
ALTER TABLE public.pos_quick_buttons
    ADD COLUMN IF NOT EXISTS ask_price boolean NOT NULL DEFAULT false;
CREATE INDEX IF NOT EXISTS ix_pos_quick_buttons_group ON public.pos_quick_buttons (group_id);

