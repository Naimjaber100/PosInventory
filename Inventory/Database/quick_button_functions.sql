-- Tabs in order with their number of buttons.
-- p_for_cashier = true: only active tabs that have at least one button the cashier can sell.
CREATE OR REPLACE FUNCTION public.fn_quick_group_get_all(p_for_cashier boolean DEFAULT true)
RETURNS TABLE (group_id integer, name varchar, color varchar, sort_order integer, is_active boolean, button_count bigint)
LANGUAGE sql STABLE
AS $$
    SELECT g.group_id, g.name, g.color, g.sort_order, g.is_active, count(b.button_id)
    FROM pos_quick_groups g
    LEFT JOIN (SELECT x.button_id, x.group_id FROM fn_quick_button_get_all(p_for_cashier) x) b ON b.group_id = g.group_id
    WHERE NOT p_for_cashier OR g.is_active
    GROUP BY g.group_id
    HAVING NOT p_for_cashier OR count(b.button_id) > 0
    ORDER BY g.sort_order, g.group_id;
$$;

-- Adds (p_group_id null, goes to the end) or updates a tab; returns its id.
CREATE OR REPLACE FUNCTION public.fn_quick_group_save(p_group_id integer, p_name text, p_color text, p_is_active boolean DEFAULT true)
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE
    v_name text := nullif(trim(p_name), '');
    v_id   integer;
BEGIN
    IF v_name IS NULL THEN
        RAISE EXCEPTION 'The tab name is required.';
    END IF;
    IF EXISTS (SELECT 1 FROM pos_quick_groups
               WHERE lower(name) = lower(v_name) AND group_id IS DISTINCT FROM p_group_id) THEN
        RAISE EXCEPTION 'A tab named "%" already exists.', v_name;
    END IF;

    IF p_group_id IS NULL THEN
        INSERT INTO pos_quick_groups (name, color, sort_order, is_active)
        VALUES (v_name, nullif(trim(p_color), ''),
                (SELECT coalesce(max(sort_order), 0) + 1 FROM pos_quick_groups), coalesce(p_is_active, true))
        RETURNING group_id INTO v_id;
    ELSE
        UPDATE pos_quick_groups
        SET name = v_name, color = nullif(trim(p_color), ''), is_active = coalesce(p_is_active, is_active)
        WHERE group_id = p_group_id
        RETURNING group_id INTO v_id;
        IF v_id IS NULL THEN
            RAISE EXCEPTION 'Tab % does not exist.', p_group_id;
        END IF;
    END IF;
    RETURN v_id;
END $$;

-- Removes a tab. p_delete_buttons = false keeps its buttons (they move to "no tab").
CREATE OR REPLACE FUNCTION public.fn_quick_group_delete(p_group_id integer, p_delete_buttons boolean DEFAULT false)
RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_delete_buttons THEN
        DELETE FROM pos_quick_buttons WHERE group_id = p_group_id;
    END IF;
    DELETE FROM pos_quick_groups WHERE group_id = p_group_id;   -- remaining buttons: group_id set null
END $$;

-- Sets the order: the tabs get sort_order 1, 2, 3... in the order of the ids given.
CREATE OR REPLACE FUNCTION public.fn_quick_group_reorder(p_group_ids integer[])
RETURNS void
LANGUAGE sql
AS $$
    UPDATE pos_quick_groups g
    SET sort_order = o.pos
    FROM unnest(p_group_ids) WITH ORDINALITY AS o(id, pos)
    WHERE g.group_id = o.id;
$$;

-- ===========================================================================
-- Settings (read with fn_setting). Used for 'pos_quick_columns' = item buttons per row.
-- ===========================================================================
CREATE OR REPLACE FUNCTION public.fn_setting_set(p_key text, p_value text)
RETURNS void
LANGUAGE sql
AS $$
    INSERT INTO settings (key, value) VALUES (p_key, coalesce(p_value, ''))
    ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value;
$$;
